/* 執行層：逐一比對文字節點與屬性，有譯文就換，沒有就維持中文。 */
(function () {
  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, TEMPLATE: 1 };
  var ATTRS = ['alt', 'title', 'placeholder'];
  var nodes = null, attrs = null, metaDesc = null, docTitle = null;

  function norm(s) { return s.trim().replace(/\s+/g, ' '); }

  function collect() {
    var w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (SKIP[n.parentNode && n.parentNode.nodeName]) return NodeFilter.FILTER_REJECT;
        return n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var a = [], n;
    while ((n = w.nextNode())) a.push([n, n.nodeValue]);
    nodes = a;
    attrs = [];
    ATTRS.forEach(function (k) {
      Array.prototype.forEach.call(document.querySelectorAll('[' + k + ']'), function (el) {
        attrs.push([el, k, el.getAttribute(k)]);
      });
    });
    var m = document.querySelector('meta[name="description"]');
    metaDesc = m ? [m, m.getAttribute('content')] : null;
    docTitle = document.title;
  }

  window.applyPageLang = function (lang) {
    if (!nodes) collect();
    var d = (window.PAGE_I18N || {})[lang] || null;
    nodes.forEach(function (p) {
      var src = p[1], v = d && d[norm(src)];
      p[0].nodeValue = v ? src.replace(src.trim(), v) : src;
    });
    attrs.forEach(function (p) {
      var v = d && d[norm(p[2])];
      p[0].setAttribute(p[1], v || p[2]);
    });
    if (metaDesc) {
      var mv = d && d[norm(metaDesc[1])];
      metaDesc[0].setAttribute('content', mv || metaDesc[1]);
    }
    document.documentElement.lang = lang === 'zh' ? 'zh-Hant' : lang;
  };
})();
